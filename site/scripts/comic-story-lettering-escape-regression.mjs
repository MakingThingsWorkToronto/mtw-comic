import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = readFileSync(new URL('./comic-story-art-review.mjs', import.meta.url), 'utf8');
const code = source.match(/function letteringEscapes\(box, limit, tolerance = 1\) \{[\s\S]*?\n              \}/)?.[0];
assert.ok(code, 'review must retain rendered lettering containment helper');
const escaped = vm.runInNewContext(`(${code})`);
const panel = [12, 672, 365, 110];
assert.equal(escaped([20, 680, 330, 45], panel), false, 'full-width three-line caption fits');
assert.equal(escaped([20, 680, 85, 240], panel), true, 'candidate02 narrow Traditional link caption exceeds panel');
assert.equal(escaped([20, 680, 85, 240], [0,0,390,844]), true, 'same caption exceeds viewport');
assert.equal(escaped([11.5,672,365,110], panel), false, 'subpixel tolerance');
assert.equal(escaped([9,672,365,110], panel), true, 'left escape');
assert.equal(escaped([12,670,365,110], panel), true, 'top escape');
assert.equal(escaped([12,672,368,110], panel), true, 'right escape');
assert.match(source, /getClientRects\(\)/, 'must measure actual rendered glyph spans');
assert.match(source, /report\.letteringCandidates/, 'must retain candidates in evidence');
assert.match(source, /textOverlapWith/, 'must inspect cross-balloon lettering overlap');
console.log('10 lettering escape checks passed');
